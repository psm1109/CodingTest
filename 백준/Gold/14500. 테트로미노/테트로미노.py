N,M = map(int,input().split())
P = [list(map(int,input().split())) for _ in range(N)]

forms = [[(0,1), (0,2), (0,3)], [(1,0), (2,0), (3,0)], # I
        [(0,1), (1,0), (1,1)], # ㅁ
        [(1,0),(1,1),(2,1)], [(0,-1), (1,-1), (1,-2)], # Z회전
        [(1,0), (1,-1), (2,-1)],[(0,1), (1,1), (1,2)], # Z대칭
        [(1,0), (2,0), (2,1)], [(0,1), (0,2), (1,0)], # L회전
        [(0,1),(1,1), (2,1)], [(0,1), (0,2), (-1,2)],
        [(1,0),(2,0),(2,-1)],[(0,1),(0,2),(1,2)], # L대칭
        [(1,0),(2,0),(0,1)], [(1,0),(1,1),(1,2)],
        [(1,0),(1,1),(1,-1)], [(1,0),(1,1),(2,0)], # ㅗ회전
        [(0,-1),(1,0),(0,1)],[(0,1),(-1,1),(1,1)] 
]

result = 0
for i in range(N): #세로
    for j in range(M): #가로 
        for f in forms:
            t = P[i][j]
            flag = 1
            for k in range(3):
                Y = i+f[k][1]
                X = j+f[k][0]
                if Y < 0 or Y >= N or X < 0 or X >= M:
                    flag = 0
                    break
                t += P[Y][X]
            if flag:
                result = max(result,t)
print(result)